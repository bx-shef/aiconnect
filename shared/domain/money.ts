// Копейки. Одно правило округления на всё приложение: цена с наценкой, сумма строки, налог и итог
// считаются так же, как их посчитает портал, — иначе предпросмотр разошёлся бы со счётом.

/**
 * Округление до копеек как у портала: половина копейки — вверх, 135,795 → 135,80, 0,825 → 0,83.
 * `Math.round(x * 100)` дал бы 135,79: 135,795 × 100 в двоичной дроби равно 13579,4999…, а портал
 * (PHP `round`) такого сдвига не делает. Поправка — до 15 значащих цифр, поэтому настоящее «меньше
 * половины» (0,0049999) остаётся вниз. Замер на портале — tests/vat.test.ts.
 */
export function roundMoney(value: number): number {
  return Math.round(Number((value * 100).toPrecision(15))) / 100
}
